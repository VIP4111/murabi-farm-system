"""طلب صريح: "أكمل في إدارة المهمات" ثم "أحتاج فقعات أكثر" — استكمال
فقعات الشرح بشاشة "المهام" (team/tasks_list.html) وفورم "توزيع مهمة"
المشترك (_task_assign_fields.html): الفرق بين "توزيع مهمة" و"مهام
العامل التلقائية"، نطاق "مهامي"، فلترة تبويبات الدور، صندوق مراجعة
المالك، مهام وزّعتها، ونوع المهمة/المكلَّف/متطلب الصورة بفورم التوزيع."""


def test_tasks_list_has_multiple_tips(app, logged_in_client):
    resp = logged_in_client.get("/team/tasks")
    body = resp.data.decode()
    assert resp.status_code == 200
    # 6 فقعات بشاشة المهام نفسها (توزيع مهمة، مهامي، فلترة الدور،
    # صندوق مراجعة المالك، مهام وزّعتها، جدول المهام المعتمدة)
    # + عمودي "النوع"/"الإجراءات" بجدولي مهامي والمقترحة (2)
    # + 3 فقعات جوه فورم "توزيع مهمة" المنبثق = 11
    assert body.count('class="info-tip"') >= 11
