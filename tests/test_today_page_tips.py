"""طلب صريح: "صفحة اليوم كويسة ناقصها فقعة الشروحات" — إضافة تلميحات
لتوضيح الفرق بين "مهامي" (تكليف) و"تنبيهاتي" (محسوبة تلقائياً، نطاقها
يعتمد على مسؤوليتك) و"بلاغاتي" (وصف رفعته أنت بنفسك)."""


def test_today_page_has_tips(app, logged_in_client):
    resp = logged_in_client.get("/today")
    body = resp.data.decode()
    assert resp.status_code == 200
    # 3 فقعات بعناوين الأقسام + فقعتين على زرّي "إدارة المهام" و"كل
    # التنبيهات" (اللي دايماً تظهر بدون بيانات) — الباقي مشروط بوجود
    # مهام/تنبيهات/بلاغات فعلية، فما نفترضها هنا.
    assert body.count('class="info-tip"') >= 5
